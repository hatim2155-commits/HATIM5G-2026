def set_language(lang: str) -> None:
    global _current_lang
    if lang in LANGUAGES:
        _current_lang = lang


def current_language() -> str:
    return _current_lang


def t(text: str) -> str:
    """Return translated string according to current language.

    The codebase uses Russian source strings as keys. For Arabic we map
    the Russian key -> Arabic text. If no translation exists, fallback to
    the original string so UI remains usable.
    """
    if _current_lang == "ru":
        return text
    if _current_lang == "ar":
        return AR.get(text, text)
    if _current_lang == "en":
        return EN.get(text, text)
    return text
